# Игра "Угадай число"
import random                           # подключаем модуль случайных чисел

secret = random.randint(1, 100)         # загадываем число от 1 до 100
attempts = 0                           # счётчик попыток
print('Добро пожаловать в Страну чисел!')
print("Я загадал число от 1 до 100.")


while True:                            # бесконечный цикл, пока не угадаем
    guess = int(input("Твой вариант: "))
    attempts += 1                      # увеличиваем счётчик на 1

    if guess < secret:
        print("Слишком мало, попробуйте еще раз!")
    elif guess > secret:
        print("Слишком много, попробуйте еще раз!")
    else:
        print("Вы угадали, поздравляем!")
        print(f"У Вас попыток: {attempts}")
        break                          # выходим из цикла
